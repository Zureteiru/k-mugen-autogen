"""Compile LyricLine data into a Karaoke Mugen (kara.moe) style .ass file.

The output mirrors the official KM Aegisub template
(https://docs.karaokes.moe/aegisub/sampleKaraokeMugen.ass) *after* "Apply karaoke template":
  - the template's styles and the templater Comment line, verbatim;
  - per lyric line, the source line as a `karaoke` Comment and the generated `fx` Dialogue
    (0.9 s lead-in filled by an empty \\k, \\fad(300,200), 0.2 s tail). Lines may overlap,
    which libass stacks at the top of the screen.
"""
import os

from models import LyricLine

LEAD_IN_MS = 900  # line appears this long before its first syllable
FADE_IN_MS = 300
TAIL_MS = 200  # line stays this long after its last syllable
FADE_OUT_MS = 200
KF_THRESHOLD_CS = 100  # syllables longer than this use progressive fill (\kf), others \k

STYLE_UP = "Sample KM [Up]"

ASS_HEADER = """[Script Info]
; Script generated by k-mugen-autogen
Title: {title}
ScriptType: v4.00+
WrapStyle: 0
PlayResX: 0
PlayResY: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Sample KM [Up],Arial,24,&H00008AFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,8,2,2,20,1
Style: Sample KM [Choir],Arial,24,&H005757FF,&H00FFFFFF,&H00000000,&H00000000,-1,-1,0,0,100,100,0,0,1,1.5,0,8,2,2,80,1
Style: Sample KM Duo [Voice 1],Arial,24,&H00FFFFFF,&H00008AFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,8,2,2,20,1
Style: Sample KM Duo [Voice 2],Arial,24,&H00FFFFFF,&H00FFB858,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,8,2,2,20,1
Style: Sample KM Duo [Voice 1&2],Arial,24,&H00FFFFFF,&H00EB4DC1,&H00000000,&H00000000,-1,-1,0,0,100,100,0,0,1,1.5,0,8,2,2,20,1
Style: Sample KM [Down],Arial,24,&H00008AFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,2,2,2,40,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

TEMPLATE_LINE = (
    "Comment: 0,0:00:00.00,0:00:00.00,Sample KM [Up],,0,0,0,template pre-line all keeptags,"
    '!retime("line",$start < 900 and -$start or -900,200)!'
    '{!$start < 900 and "\\\\k" .. ($start/10) or "\\\\k90"!\\fad(!$start < 900 and $start or 300!,200)}'
)


def _format_ass_time(seconds: float) -> str:
    """Format seconds into ASS timestamp format H:MM:SS.cs."""
    seconds = max(0.0, seconds)
    total_cs = int(round(seconds * 100))
    cs = total_cs % 100
    total_s = total_cs // 100
    s = total_s % 60
    total_m = total_s // 60
    m = total_m % 60
    h = total_m // 60
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def _build_romaji_payload(line: LyricLine, event_start_sec: float) -> str:
    """
    Assemble the karaoke payload with continuous, drift-free centisecond tracking from
    event_start_sec. Gaps become empty {\\kN}; syllables use \\k, or \\kf when longer than
    KF_THRESHOLD_CS (the KM convention).
    """
    payload_parts: list[str] = []
    current_sec = event_start_sec

    for m in line.morae:
        m_start = max(current_sec, m.start_sec)
        m_end = max(m_start + 0.05, m.end_sec)

        gap_cs = int(round((m_start - current_sec) * 100))
        if gap_cs > 0:
            payload_parts.append(f"{{\\k{gap_cs}}}")
            current_sec += gap_cs / 100.0

        dur_cs = max(1, int(round((m_end - current_sec) * 100)))
        tag = "kf" if dur_cs > KF_THRESHOLD_CS else "k"
        payload_parts.append(f"{{\\{tag}{dur_cs}}}{m.romaji}")
        current_sec += dur_cs / 100.0

    return "".join(payload_parts)


def _line_bounds(line: LyricLine) -> tuple[float, float]:
    """Sung span of a line: first syllable start to last syllable end."""
    if line.morae:
        return line.morae[0].start_sec, max(line.morae[-1].end_sec, line.morae[0].start_sec + 0.05)
    return line.start_sec, line.end_sec


def compile_ass(lines: list[LyricLine], title: str, output_path: str) -> str:
    """
    Compile LyricLines into a Karaoke Mugen-style ASS file (UTF-8 with BOM) and return the content.
    """
    events: list[str] = [TEMPLATE_LINE]

    for line in lines:
        start, end = _line_bounds(line)
        start = round(max(0.0, start), 2)  # centisecond grid, so lead + payload add up exactly
        start_ms = int(round(start * 1000))

        # Source line, kept as Aegisub leaves it after applying the template
        src_payload = _build_romaji_payload(line, event_start_sec=start)
        events.append(
            f"Comment: 0,{_format_ass_time(start)},{_format_ass_time(end)},{STYLE_UP},,0,0,0,karaoke,{src_payload}"
        )

        # Generated line: retime("line", -lead, +tail) with the lead filled by an empty \k
        lead_ms = min(start_ms, LEAD_IN_MS)
        fade_in = start_ms if start_ms < LEAD_IN_MS else FADE_IN_MS  # same branch as the template
        fx_start = (start_ms - lead_ms) / 1000.0
        fx_end = end + TAIL_MS / 1000.0
        prefix = f"{{\\k{lead_ms // 10}\\fad({fade_in},{FADE_OUT_MS})}}"
        events.append(
            f"Dialogue: 0,{_format_ass_time(fx_start)},{_format_ass_time(fx_end)},{STYLE_UP},,0,0,0,fx,"
            f"{prefix}{src_payload}"
        )

    ass_content = ASS_HEADER.format(title=title) + "\n".join(events) + "\n"

    output_dir = os.path.dirname(os.path.abspath(output_path))
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    with open(output_path, "w", encoding="utf-8-sig") as f:
        f.write(ass_content)

    return ass_content
