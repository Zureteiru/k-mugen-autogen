import os
import pykakasi
from japanese_utils import get_morae_for_text
from models import LyricLine, MoraTiming

_SMALL_KANA = set("ゃゅょぁぃぅぇぉゎャュョァィゥェォヮ")


def _format_ass_time(seconds: float) -> str:
    """Format seconds into ASS timestamp format H:MM:SS.cs."""
    seconds = max(0.0, seconds)
    total_cs = int(round(seconds * 100))
    cs = total_cs % 100
    total_s = total_cs // 100
    s = total_s % 60
    total_m = total_s // 60
    m = total_m % 60
    h = total_m // 60
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def _apply_word_spaces(original_text: str, morae: list[MoraTiming]) -> list[str]:
    """
    Ensure spaces are cleanly inserted between words in the morae list
    based on word boundaries in original_text.
    """
    words = original_text.split()
    if len(words) <= 1 or not morae:
        return [m.romaji for m in morae]

    k = pykakasi.kakasi()
    word_mora_counts: list[int] = []
    for w in words:
        conv = k.convert(w)
        h = "".join(t.get("hira", "") for t in conv)
        chars = [c for c in h if not c.isspace() and c not in "、。・！？…〜~\"'()[]{}"]
        cnt = 0
        i = 0
        while i < len(chars):
            if i + 1 < len(chars) and chars[i + 1] in _SMALL_KANA:
                i += 2
            else:
                i += 1
            cnt += 1
        word_mora_counts.append(cnt)

    if sum(word_mora_counts) == len(morae):
        result = []
        cur_idx = 0
        for w_idx, count in enumerate(word_mora_counts):
            for j in range(count):
                m_rom = morae[cur_idx].romaji
                if j == count - 1 and w_idx < len(word_mora_counts) - 1:
                    if not m_rom.endswith(" "):
                        m_rom = m_rom + " "
                result.append(m_rom)
                cur_idx += 1
        return result

    return [m.romaji for m in morae]


def _build_romaji_payload(line: LyricLine, event_start_sec: float) -> str:
    """
    Assemble the Romaji karaoke payload string with continuous, drift-free timeline tracking.
    Every mora or word begins highlighting at its exact acoustic centisecond.
    """
    has_spaces = any(" " in m.romaji for m in line.morae)
    if has_spaces:
        romaji_list = [m.romaji for m in line.morae]
    else:
        romaji_list = _apply_word_spaces(line.original_text, line.morae)

    payload_parts: list[str] = []
    current_sec = event_start_sec

    for m, rom in zip(line.morae, romaji_list):
        m_start = max(current_sec, m.start_sec)
        m_end = max(m_start + 0.05, m.end_sec)

        # Gap between current timeline position and this mora's start
        gap_cs = int(round((m_start - current_sec) * 100))
        if gap_cs > 0:
            payload_parts.append(f"{{\\k{gap_cs}}}")
            current_sec += gap_cs / 100.0

        # Duration for this mora
        dur_cs = max(1, int(round((m_end - current_sec) * 100)))
        payload_parts.append(f"{{\\kf{dur_cs}}}{rom}")
        current_sec += dur_cs / 100.0

    return "".join(payload_parts)


def compile_ass(lines: list[LyricLine], title: str, output_path: str) -> str:
    """
    Compile a list of LyricLine objects into a Karaoke Mugen-style ASS subtitle file.
    Writes to output_path with UTF-8 BOM (utf-8-sig) encoding and returns the content.
    """
    header = f"""[Script Info]
; Script generated by k-mugen-autogen
Title: {title}
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Romaji,Arial Bold,68,&H0000FFFF,&H00FFFFFF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,4,2,2,10,10,85,1
Style: Kanji,Noto Sans CJK JP Bold,42,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,-1,0,0,0,100,100,0,0,1,3,2,2,10,10,165,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    dialogue_lines: list[str] = []

    for idx, line in enumerate(lines):
        start_sec = max(0.0, line.start_sec - 0.50)
        end_sec = line.end_sec + 1.20
        if idx + 1 < len(lines):
            next_start = lines[idx + 1].start_sec
            if end_sec > next_start - 0.15:
                end_sec = max(line.end_sec + 0.10, next_start - 0.15)

        start_str = _format_ass_time(start_sec)
        end_str = _format_ass_time(end_sec)

        # Romaji karaoke dialogue (Japanese ruby text removed)
        romaji_payload = _build_romaji_payload(line, event_start_sec=start_sec)
        romaji_dialogue = f"Dialogue: 0,{start_str},{end_str},Romaji,,0,0,0,,{romaji_payload}"
        dialogue_lines.append(romaji_dialogue)

    ass_content = header + "\n".join(dialogue_lines) + "\n"

    output_dir = os.path.dirname(os.path.abspath(output_path))
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    with open(output_path, "w", encoding="utf-8-sig") as f:
        f.write(ass_content)

    return ass_content
